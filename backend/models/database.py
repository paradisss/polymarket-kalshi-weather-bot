"""Database models and connection for BTC 5-min trading bot."""
from datetime import datetime
from typing import Optional
from sqlalchemy import create_engine, Column, Integer, String, Float, DateTime, Boolean, JSON, text
from sqlalchemy.ext.declarative import declarative_base
from sqlalchemy.orm import sessionmaker
from sqlalchemy import inspect
import enum

from backend.config import settings

engine = create_engine(
    settings.DATABASE_URL,
    connect_args={"check_same_thread": False} if "sqlite" in settings.DATABASE_URL else {}
)
SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)
Base = declarative_base()


class Trade(Base):
    """Simulated trades for tracking P&L."""
    __tablename__ = "trades"

    id = Column(Integer, primary_key=True, index=True)
    signal_id = Column(Integer, index=True)
    market_ticker = Column(String, index=True)
    platform = Column(String)
    event_slug = Column(String, nullable=True)
    market_type = Column(String, default="btc", index=True)  # "btc" or "weather"

    # Trade details
    direction = Column(String)  # "up" or "down"
    entry_price = Column(Float)
    size = Column(Float)
    timestamp = Column(DateTime, default=datetime.utcnow)

    # Settlement
    settled = Column(Boolean, default=False)
    settlement_time = Column(DateTime, nullable=True)
    settlement_value = Column(Float, nullable=True)  # 1.0=Up won, 0.0=Down won
    result = Column(String, default="pending")  # pending, win, loss
    pnl = Column(Float, nullable=True)

    # Model performance tracking
    model_probability = Column(Float)
    market_price_at_entry = Column(Float)
    edge_at_entry = Column(Float)


class BtcPriceSnapshot(Base):
    """Cached BTC prices for momentum calculation."""
    __tablename__ = "btc_price_snapshots"

    id = Column(Integer, primary_key=True, index=True)
    timestamp = Column(DateTime, default=datetime.utcnow, index=True)
    price = Column(Float)
    source = Column(String, default="coingecko")


class BotState(Base):
    """Bot state and statistics."""
    __tablename__ = "bot_state"

    id = Column(Integer, primary_key=True)
    bankroll = Column(Float, default=10000.0)
    total_trades = Column(Integer, default=0)
    winning_trades = Column(Integer, default=0)
    total_pnl = Column(Float, default=0.0)
    last_run = Column(DateTime, nullable=True)
    is_running = Column(Boolean, default=False)


class Signal(Base):
    """Trading signals generated by the bot."""
    __tablename__ = "signals"

    id = Column(Integer, primary_key=True, index=True)
    market_ticker = Column(String, index=True)
    platform = Column(String)
    market_type = Column(String, default="btc", index=True)  # "btc" or "weather"
    timestamp = Column(DateTime, default=datetime.utcnow, index=True)

    direction = Column(String)
    model_probability = Column(Float)
    market_price = Column(Float)
    edge = Column(Float)
    confidence = Column(Float)

    kelly_fraction = Column(Float)
    suggested_size = Column(Float)

    sources = Column(JSON)
    reasoning = Column(String)

    executed = Column(Boolean, default=False)

    # Calibration tracking — filled after settlement
    actual_outcome = Column(String, nullable=True)    # "up" or "down" — actual market result
    outcome_correct = Column(Boolean, nullable=True)   # did our direction prediction match?
    settlement_value = Column(Float, nullable=True)     # 1.0=UP won, 0.0=DOWN won
    settled_at = Column(DateTime, nullable=True)        # when we recorded the outcome


class SurvivalTrade(Base):
    """Survival mode: paper trades of candidate strategies, priced at the ask with Polymarket's
    crypto taker fee, so each strategy has to prove it survives costs before any real money."""
    __tablename__ = "survival_trades"

    id = Column(Integer, primary_key=True, index=True)
    strategy = Column(String, index=True)
    venue = Column(String, default="polymarket_us", index=True)
    market_id = Column(String, index=True)
    slug = Column(String, nullable=True)
    timeframe = Column(String, index=True)
    window_end = Column(DateTime, nullable=True)
    opened_at = Column(DateTime, default=datetime.utcnow, index=True)

    direction = Column(String)          # "up" or "down"
    entry_price = Column(Float)         # ask paid for the chosen side (0-1)
    mid_at_entry = Column(Float)        # market mid probability of the chosen side
    model_at_entry = Column(Float, nullable=True)  # price-model probability of the chosen side
    elapsed_frac = Column(Float)
    shares = Column(Float)
    stake = Column(Float)               # cash spent incl. fee
    fee = Column(Float)

    settled = Column(Boolean, default=False, index=True)
    settled_at = Column(DateTime, nullable=True)
    outcome = Column(String, nullable=True)   # "up" or "down"
    result = Column(String, default="pending")  # pending, win, loss
    pnl = Column(Float, nullable=True)
    exit_price = Column(Float, nullable=True)   # bid sold at (take-profit / stop) - None if held to settlement
    exit_reason = Column(String, nullable=True)  # "take_profit", "stop_loss", "settled"
    fee_coef = Column(Float, nullable=True)        # venue taker fee coefficient at entry
    price_to_beat = Column(Float, nullable=True)   # window open on the settlement index
    index_at_entry = Column(Float, nullable=True)  # settlement index (BRTI) when the trade opened


class LiveTrade(Base):
    """Real-money orders on Polymarket US, mirrored from PROVEN survival strategies only."""
    __tablename__ = "live_trades"

    id = Column(Integer, primary_key=True, index=True)
    strategy = Column(String, index=True)
    slug = Column(String, index=True)
    timeframe = Column(String)
    window_end = Column(DateTime, nullable=True)
    opened_at = Column(DateTime, default=datetime.utcnow, index=True)
    direction = Column(String)
    limit_price = Column(Float)          # side price we were willing to pay
    quantity = Column(Integer)           # shares requested
    filled = Column(Float, default=0.0)  # shares filled
    avg_price = Column(Float, nullable=True)
    cost = Column(Float, default=0.0)    # cash spent incl. fee (estimated from fills)
    order_id = Column(String, nullable=True)
    status = Column(String, default="new")  # new, filled, partial, unfilled, rejected, error
    error = Column(String, nullable=True)
    exit_order_id = Column(String, nullable=True)
    exit_price = Column(Float, nullable=True)
    settled = Column(Boolean, default=False, index=True)
    settled_at = Column(DateTime, nullable=True)
    outcome = Column(String, nullable=True)
    pnl = Column(Float, nullable=True)


